"""Physics-informed head evaluation — does writing physics INTO the architecture
(a Hamiltonian head + symplectic integrator) beat an unstructured net at learning
conservative dynamics, measured on PHYSICS metrics (never perplexity)?

This is the honest, self-contained test of the one place the PINN investigation
found physics-informed ML genuinely applies: CONTINUOUS-STATE trajectory
prediction. It has nothing to do with language / hallucination (a category error,
see mt_lnn/hamiltonian_head.py) — ground truth is a conservative mechanical
system, the models predict phase state (q, p), and we score k-step rollout MSE and
ENERGY DRIFT over held-out trajectories.

Two models, matched budget, same optimizer/lr/steps, trained on 1-step MSE:
  * HamiltonianHead  — learns H(q,p)=T(p)+V(q), velocity-Verlet symplectic step;
                       energy conserved by CONSTRUCTION (hard constraint).
  * MLPFieldHead     — unstructured field f(q,p)->(q_dot,p_dot), plain Euler;
                       the honest control (no conservation structure).

Systems (--system):
  spring : 2D harmonic oscillator, EXACT analytic ground truth (no integrator
           error) — canonical HNN test, fast and robust. Default.
  orbit  : 2-body softened-gravity orbit generated by mt_lnn/physics_ops.py
           (integrate_verlet + pairwise_gravity) — uses our own exact engine.

Hypothesis (falsifiable): the Hamiltonian head should show DRAMATICALLY lower
long-horizon energy drift at equal short-horizon fit. If it does not, the
structure buys nothing here and the idea is shelved. CPU-runnable.

Usage:
    python benchmarks/physics_rollout_eval.py --system spring --train_steps 800
"""

from __future__ import annotations

import argparse
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch

from mt_lnn.hamiltonian_head import HamiltonianHead, MLPFieldHead


# ---------------------------------------------------------------------------
# Ground-truth conservative systems
# ---------------------------------------------------------------------------

def gen_spring(n_traj, steps, dt, dim, omega, g):
    """2D (or dim-D) harmonic oscillator, EXACT analytic rollout. Per DOF:
       q(t) = q0 cos(wt) + (p0/w) sin(wt);  p(t) = -q0 w sin(wt) + p0 cos(wt).
    Returns qs, ps: (n_traj, steps+1, dim). Energy = 0.5|p|^2 + 0.5 w^2 |q|^2."""
    q0 = torch.randn(n_traj, dim, generator=g)
    p0 = torch.randn(n_traj, dim, generator=g)
    t = torch.arange(steps + 1, dtype=torch.float32) * dt      # (steps+1,)
    wt = omega * t                                             # (steps+1,)
    c, s = torch.cos(wt), torch.sin(wt)                        # (steps+1,)
    # broadcast: (steps+1,1,1) x (1,n_traj,dim)
    c = c.view(-1, 1, 1); s = s.view(-1, 1, 1)
    q0b = q0.unsqueeze(0); p0b = p0.unsqueeze(0)
    qs = q0b * c + (p0b / omega) * s
    ps = -q0b * omega * s + p0b * c
    return qs.transpose(0, 1).contiguous(), ps.transpose(0, 1).contiguous()


def spring_energy(q, p, omega):
    return 0.5 * (p ** 2).sum(-1) + 0.5 * omega ** 2 * (q ** 2).sum(-1)


def gen_orbit(n_traj, steps, dt, g, G=1.0, softening=0.1):
    """2-body softened-gravity orbits via mt_lnn/physics_ops.py (unit masses, so
    momentum == velocity). COM held at rest (total momentum zero) so orbits stay
    bound and centred. State per traj flattened to q=positions(4), p=velocities(4).
    Returns qs, ps: (n_traj, steps+1, 4). Uses the repo's exact symplectic engine
    as ground truth."""
    from mt_lnn.physics_ops import integrate_verlet, pairwise_gravity, kinetic_energy

    mass = torch.ones(2)
    # random bound-ish initial conditions, COM at origin & at rest
    r = 0.6 + 0.4 * torch.rand(n_traj, 1, generator=g)                # separation/2
    ang = 2 * math.pi * torch.rand(n_traj, 1, generator=g)
    pos1 = torch.cat([r * torch.cos(ang), r * torch.sin(ang)], dim=-1)  # (n,2)
    pos = torch.stack([pos1, -pos1], dim=1)                          # (n,2 bodies,2)
    # circular-ish speed for a bound orbit, opposite velocities (zero COM momentum)
    v_mag = torch.sqrt(torch.tensor(G) / (2 * r).clamp_min(1e-3))    # (n,1)
    vel1 = torch.cat([-v_mag * torch.sin(ang), v_mag * torch.cos(ang)], dim=-1)
    vel = torch.stack([vel1, -vel1], dim=1)                          # (n,2,2)

    def accel(p_):                                                   # p_: (n,2,2)
        return pairwise_gravity(p_, mass, G=G, softening=softening)

    qs, ps = [pos.clone()], [vel.clone()]
    a = accel(pos)
    for _ in range(steps):
        pos, vel, a = integrate_verlet(pos, vel, accel, dt, accel=a)
        qs.append(pos.clone()); ps.append(vel.clone())
    q = torch.stack(qs, dim=1).reshape(n_traj, steps + 1, 4)
    p = torch.stack(ps, dim=1).reshape(n_traj, steps + 1, 4)
    return q, p, {"mass": mass, "G": G, "softening": softening}


def orbit_energy(q, p, meta):
    """KE + softened pairwise-gravity PE for the flattened 2-body state."""
    G, eps = meta["G"], meta["softening"]
    pos = q.reshape(*q.shape[:-1], 2, 2)
    vel = p.reshape(*p.shape[:-1], 2, 2)
    ke = 0.5 * (vel ** 2).sum(dim=(-1, -2))
    r = (pos[..., 0, :] - pos[..., 1, :]).pow(2).sum(-1).add(eps ** 2).sqrt()
    pe = -G * 1.0 * 1.0 / r
    return ke + pe


# ---------------------------------------------------------------------------
# Train / eval
# ---------------------------------------------------------------------------

def train_head(head, qs, ps, steps, lr, batch, dt, seed):
    """Supervised 1-step MSE: predict (q_{t+1}, p_{t+1}) from (q_t, p_t)."""
    g = torch.Generator().manual_seed(seed)
    opt = torch.optim.Adam(head.parameters(), lr=lr)
    N, T = qs.shape[0], qs.shape[1] - 1
    head.train()
    for step in range(1, steps + 1):
        ti = torch.randint(0, N, (batch,), generator=g)
        tt = torch.randint(0, T, (batch,), generator=g)
        q0, p0 = qs[ti, tt], ps[ti, tt]
        q1, p1 = qs[ti, tt + 1], ps[ti, tt + 1]
        q_pred, p_pred = head.step(q0, p0, dt)
        loss = ((q_pred - q1) ** 2 + (p_pred - p1) ** 2).mean()
        opt.zero_grad(set_to_none=True)
        loss.backward()
        opt.step()
    return loss.item()


@torch.no_grad()
def _energy(system, q, p, omega, meta):
    return spring_energy(q, p, omega) if system == "spring" else orbit_energy(q, p, meta)


def eval_rollout(head, qs, ps, k, dt, system, omega, meta):
    """From each held-out initial state, roll the MODEL k steps and compare to the
    ground-truth continuation. Report k-step rollout MSE and relative energy drift
    (|E_k - E_0| / |E_0|), averaged over trajectories."""
    head.eval()
    q0, p0 = qs[:, 0], ps[:, 0]
    with torch.enable_grad():                       # field is an autograd gradient
        qroll, proll = head.rollout(q0, p0, k, dt)  # (k+1, n, dim)
    qroll, proll = qroll.detach(), proll.detach()
    q_true, p_true = qs[:, :k + 1].transpose(0, 1), ps[:, :k + 1].transpose(0, 1)
    rollout_mse = ((qroll - q_true) ** 2 + (proll - p_true) ** 2).mean().item()
    E = _energy(system, qroll, proll, omega, meta)  # (k+1, n)
    E0 = E[0].abs().clamp_min(1e-6)
    drift = ((E - E[0]).abs() / E0).mean(-1)        # (k+1,)
    return {"rollout_mse": rollout_mse,
            "energy_drift_final": drift[-1].item(),
            "energy_drift_max": drift.max().item()}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--system", choices=["spring", "orbit"], default="spring")
    ap.add_argument("--n_train", type=int, default=512)
    ap.add_argument("--n_eval", type=int, default=128)
    ap.add_argument("--gen_steps", type=int, default=200)
    ap.add_argument("--eval_k", type=int, default=200, help="rollout horizon")
    ap.add_argument("--dt", type=float, default=0.1)
    ap.add_argument("--dim", type=int, default=2, help="spring only (orbit is fixed at 4)")
    ap.add_argument("--omega", type=float, default=1.0, help="spring frequency")
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--train_steps", type=int, default=800)
    ap.add_argument("--lr", type=float, default=3e-3)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out_dir", default="benchmarks/physics_out")
    args = ap.parse_args()

    g = torch.Generator().manual_seed(args.seed)
    meta = {}
    if args.system == "spring":
        dim = args.dim
        qs, ps = gen_spring(args.n_train + args.n_eval, args.gen_steps, args.dt,
                            dim, args.omega, g)
    else:
        dim = 4
        qs, ps, meta = gen_orbit(args.n_train + args.n_eval, args.gen_steps,
                                 args.dt, g)
    tr = slice(0, args.n_train); ev = slice(args.n_train, None)
    qs_tr, ps_tr = qs[tr], ps[tr]
    qs_ev, ps_ev = qs[ev], ps[ev]
    print(f"system={args.system} dim={dim} dt={args.dt} train={args.n_train} "
          f"eval={args.n_eval} k={args.eval_k}", flush=True)

    results = {}
    for name, Head in (("hamiltonian", HamiltonianHead), ("mlp_field", MLPFieldHead)):
        torch.manual_seed(args.seed)               # matched init stream per model
        head = Head(dim, hidden_dim=args.hidden, depth=2)
        n_par = sum(p.numel() for p in head.parameters())
        final_loss = train_head(head, qs_tr, ps_tr, args.train_steps, args.lr,
                                args.batch, args.dt, args.seed)
        res = eval_rollout(head, qs_ev, ps_ev, args.eval_k, args.dt,
                           args.system, args.omega, meta)
        res.update({"params": n_par, "train_loss": round(final_loss, 6)})
        results[name] = res
        print(f"  [{name:11s}] params {n_par:>6,} | 1-step loss {final_loss:.4e} | "
              f"rollout_mse {res['rollout_mse']:.4e} | energy_drift(final) "
              f"{res['energy_drift_final']:.4e} | (max) {res['energy_drift_max']:.4e}",
              flush=True)

    os.makedirs(args.out_dir, exist_ok=True)
    out = {"system": args.system, "args": vars(args), "results": results}
    with open(os.path.join(args.out_dir, f"physics_rollout_{args.system}.json"), "w") as f:
        json.dump(out, f, indent=2)

    h, m = results["hamiltonian"], results["mlp_field"]
    print("\n" + "=" * 66, flush=True)
    print("PHYSICS-INFORMED HEAD | Hamiltonian (hard-constraint) vs MLP-field control",
          flush=True)
    print("=" * 66, flush=True)
    drift_ratio = m["energy_drift_final"] / max(h["energy_drift_final"], 1e-9)
    mse_ratio = m["rollout_mse"] / max(h["rollout_mse"], 1e-9)
    print(f"  energy drift (final):  HNN {h['energy_drift_final']:.3e}  vs  "
          f"MLP {m['energy_drift_final']:.3e}   ({drift_ratio:.1f}x better)", flush=True)
    print(f"  {args.eval_k}-step rollout MSE:  HNN {h['rollout_mse']:.3e}  vs  "
          f"MLP {m['rollout_mse']:.3e}   ({mse_ratio:.1f}x better)", flush=True)
    verdict = ("STRUCTURE HELPS" if h["energy_drift_final"] < m["energy_drift_final"]
               and h["rollout_mse"] <= m["rollout_mse"] * 1.5 else "INCONCLUSIVE / shelve")
    print(f"  verdict: {verdict}", flush=True)


if __name__ == "__main__":
    main()
